require('../src/loadEnv')();
const assert = require('node:assert/strict');
if (process.env.NODE_ENV !== 'test' || process.env.QA_MODE !== 'true' || process.env.QA_ENVIRONMENT_SAFE !== 'true') throw Error('Isolated QA required');
const { prisma } = require('../src/prismaClient');
const automation = require('../src/business/finance/MonthlyAutomationBusiness');
const { setSetting } = require('../src/services/systemSettingService');
(async () => {
  const now = new Date('2030-04-15T12:00:00Z');
  const active = await prisma.client.create({ data: { name: 'Automation QA active', status: 'ACTIVE', active: true, billingActive: true, monthlyFee: 80 } });
  const paused = await prisma.client.create({ data: { name: 'Automation QA paused', status: 'PAUSED', active: true, billingActive: true, monthlyFee: 80 } });
  const clientIds = [active.id, paused.id];
  await setSetting('AUTO_MONTHLY_BILLING_ENABLED', 'false');
  assert.equal((await automation.monthly({ now, clientIds })).created, 0);
  const preview = await automation.monthly({ now, clientIds, preview: true });
  assert.equal(preview.candidates.length, 1); assert.equal(preview.candidates[0].amount, 80);
  assert.equal(await prisma.invoice.count({ where: { clientId: { in: clientIds } } }), 0);
  await setSetting('AUTO_MONTHLY_BILLING_ENABLED', 'true');
  await Promise.all([automation.monthly({ now, clientIds }), automation.monthly({ now, clientIds })]);
  await automation.monthly({ now, clientIds });
  const invoices = await prisma.invoice.findMany({ where: { clientId: { in: clientIds } }, include: { lines: true } });
  assert.equal(invoices.length, 1); assert.equal(invoices[0].status, 'DRAFT'); assert.equal(invoices[0].total, 80); assert.equal(invoices[0].lines.length, 1);
  console.log('PASS disabled mode, read-only preview, paused client and repeated/concurrent monthly draft generation');
  const invoice = invoices[0];
  await prisma.invoice.update({ where: { id: invoice.id }, data: { status: 'PENDING', dueDate: new Date(now.getTime() - 6 * 86400000) } });
  await setSetting('PAYMENT_REMINDERS_ENABLED', 'true');
  assert.equal((await automation.reminders({ now, clientIds })).created, 0);
  await prisma.invoice.update({ where: { id: invoice.id }, data: { dueDate: new Date(now.getTime() - 7 * 86400000) } });
  await Promise.all([automation.reminders({ now, clientIds }), automation.reminders({ now, clientIds })]);
  const where = { clientId: active.id, eventType: 'FINANCE_PAYMENT_REMINDER' };
  assert.equal(await prisma.notification.count({ where }), 1);
  await automation.reminders({ now: new Date(now.getTime() + 7 * 86400000), clientIds });
  assert.equal(await prisma.notification.count({ where }), 2);
  await prisma.client.update({ where: { id: active.id }, data: { status: 'PAUSED' } });
  await automation.reminders({ now: new Date(now.getTime() + 14 * 86400000), clientIds });
  assert.equal(await prisma.notification.count({ where }), 2);
  await prisma.client.update({ where: { id: active.id }, data: { status: 'ACTIVE' } });
  await prisma.invoice.update({ where: { id: invoice.id }, data: { status: 'PAID', amountOpen: 0, amountPaid: 80 } });
  await automation.reminders({ now: new Date(now.getTime() + 21 * 86400000), clientIds });
  assert.equal(await prisma.notification.count({ where }), 2);
  console.log('PASS reminders start at day seven, deduplicate concurrency, repeat weekly and stop on pause/payment');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  await setSetting('AUTO_MONTHLY_BILLING_ENABLED', 'false'); await setSetting('PAYMENT_REMINDERS_ENABLED', 'false'); await prisma.$disconnect();
});
